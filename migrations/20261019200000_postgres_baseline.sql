-- +goose Up
-- Postgres baseline: the schema produced by all MySQL migrations up to 20260621224500
-- (the old MySQL migrations are in git history), translated to Postgres.
-- Type mapping: tinyint(1) -> BOOLEAN, ENUM -> VARCHAR + CHECK, DATETIME -> TIMESTAMPTZ(0) in UTC,
-- JSON -> JSONB, FLOAT -> DOUBLE PRECISION, unsigned ints -> INTEGER/BIGINT.
-- On prod the data is copied from MySQL by scripts/migrate-mysql-to-postgres.js, which truncates
-- the seed rows below and keeps the original ids.

-- MySQL "ON UPDATE CURRENT_TIMESTAMP" equivalent: like MySQL, only when the row actually
-- changes and the statement did not set updated_at itself
-- +goose StatementBegin
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
	IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
		NEW.updated_at = CURRENT_TIMESTAMP;
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- +goose StatementEnd

